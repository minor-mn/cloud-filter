#!/usr/bin/env bash
# ==============================================================================
# install_cron.sh
# /etc/cron.d/cloud-filter に日次更新 & OS起動時自動適用ジョブを登録・削除します
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CRON_FILE="/etc/cron.d/cloud-filter"
LOG_FILE="${LOG_FILE:-/var/log/cloud-filter.log}"
CRON_SCHEDULE="${CRON_SCHEDULE:-35 3 * * *}"

if [[ "${EUID:-$(id -u)}" -ne 0 ]]; then
    echo "ERROR: root権限で実行してください (例: sudo $0)" >&2
    exit 1
fi

if [[ "${1:-}" == "--uninstall" || "${1:-}" == "remove" ]]; then
    if [[ -f "${CRON_FILE}" ]]; then
        rm -f "${CRON_FILE}"
        echo "削除完了: ${CRON_FILE} を削除しました。"
    else
        echo "${CRON_FILE} は存在しません。"
    fi
    exit 0
fi

chmod +x "${SCRIPT_DIR}/cloud-filter.sh" "${SCRIPT_DIR}/build_cidr_list.rb"

# sudo 実行元のユーザーまたは root の anyenv/rbenv パスを引き継ぐ
SUDO_USER_HOME=""
if [[ -n "${SUDO_USER:-}" ]]; then
    SUDO_USER_HOME="$(eval echo "~${SUDO_USER}" 2>/dev/null || true)"
fi

DETECTED_RBENV_ROOT=""
for candidate in \
    "${RBENV_ROOT:-}" \
    "${HOME}/.anyenv/envs/rbenv" \
    "${SUDO_USER_HOME:+"${SUDO_USER_HOME}/.anyenv/envs/rbenv"}" \
    "/opt/anyenv/envs/rbenv" \
    "${HOME}/.rbenv" \
    "${SUDO_USER_HOME:+"${SUDO_USER_HOME}/.rbenv"}"; do
    if [[ -n "${candidate}" && -d "${candidate}/shims" ]]; then
        DETECTED_RBENV_ROOT="${candidate}"
        break
    fi
done

CRON_PATH="/usr/local/sbin:/usr/local/bin:/sbin:/bin:/usr/sbin:/usr/bin"
if [[ -n "${DETECTED_RBENV_ROOT}" ]]; then
    CRON_PATH="${DETECTED_RBENV_ROOT}/shims:${DETECTED_RBENV_ROOT}/bin:${CRON_PATH}"
fi

cat > "${CRON_FILE}" <<EOF
# Auto-generated by ${SCRIPT_DIR}/install_cron.sh
# Upstream repo updates daily at 02:00 UTC
SHELL=/bin/bash
${DETECTED_RBENV_ROOT:+RBENV_ROOT=${DETECTED_RBENV_ROOT}}
PATH=${CRON_PATH}

@reboot root "${SCRIPT_DIR}/cloud-filter.sh" apply >> "${LOG_FILE}" 2>&1
${CRON_SCHEDULE} root "${SCRIPT_DIR}/cloud-filter.sh" update >> "${LOG_FILE}" 2>&1
EOF

chmod 0644 "${CRON_FILE}"
touch "${LOG_FILE}"
chmod 0640 "${LOG_FILE}"

echo "======================================================================"
echo " cron 登録が完了しました: ${CRON_FILE}"
echo "----------------------------------------------------------------------"
cat "${CRON_FILE}"
echo "======================================================================"
echo "ログ出力先: ${LOG_FILE}"
echo "解除する場合: sudo $0 --uninstall"
